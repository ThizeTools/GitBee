<script lang="ts">
  // Mirror CommitDetailsPanel's layout — same bar / subject / author /
  // parent / files-bar / files-body shape — but driven by a stash entry
  // and with stash-specific actions at the bottom (Apply / Pop / Edit /
  // Delete) instead of the commit toolbar (Cherry-pick / Revert / etc).
  //
  // The stash's "author" comes from the underlying graph node (which
  // for a stash is the WIP merge commit). The subject is the *cleaned*
  // stash message — git autogenerates "WIP on master: …" / "On master:
  // …" prefixes which are noise in this view.
  import { graph, currentRepo, stashes, withBusy } from "$lib/stores/repo";
  import { ipc } from "$lib/ipc";
  import DiffViewer from "./DiffViewer.svelte";
  import { diffPrefs } from "$lib/stores/diffPrefs";
  import { stashRevs } from "$lib/diff/revs";
  import Avatar from "./Avatar.svelte";
  import { showCommitFile } from "$lib/stores/center";
  import { promptDialog } from "$lib/stores/dialog";
  import { dropStashAt } from "$lib/menus/stashActions";
  import Icon from "$lib/icons/Icon.svelte";
  import type { FileDiff, GraphNode } from "$lib/ipc";

  interface Props { index: number; onClose: () => void; }
  let { index, onClose }: Props = $props();

  let diffs = $state<FileDiff[]>([]);
  let loading = $state(false);
  let viewMode = $state<"path" | "tree">("tree");
  type SortMode = "asc" | "desc";
  let sortMode = $state<SortMode>("asc");
  let allExpanded = $state(true);
  let showDiffs = $state(false);

  const entry = $derived($stashes.find((s) => s.index === index) ?? null);
  const node = $derived.by<GraphNode | null>(() => {
    if (!$graph || !entry) return null;
    return $graph.nodes.find((n) => n.sha === entry.sha) ?? null;
  });

  // Strip git's autogenerated prefixes from stash subjects so the title
  // reads as the actual change. Two shapes need to be handled:
  //   "WIP|Index|Untracked files on <branch>: <subject>"
  //   "On <branch>: <user message>"   (auto-stash variant; only one "on")
  function cleanedSubject(): string {
    const raw = entry?.message ?? "";
    let m = raw.match(/^(?:WIP|Index|Untracked files)\s+on\s+[^:]+:\s*(.+)$/i);
    if (m) return m[1];
    m = raw.match(/^On\s+[^:]+:\s*(.+)$/i);
    if (m) return m[1];
    return raw;
  }

  $effect(() => {
    void index; void $diffPrefs.ignoreWs;
    if ($currentRepo && entry) load();
  });

  async function load() {
    if (!$currentRepo || !entry) return;
    loading = true;
    // `git show <stash-sha>` returns a combined diff (stash is a 3-parent
    // merge of HEAD + index + untracked) which is almost always empty.
    // `git stash show -p stash@{N}` is the right one.
    try { diffs = await ipc.diffStash($currentRepo, index, $diffPrefs.ignoreWs); }
    catch { diffs = []; }
    finally { loading = false; }
  }

  // ----- stash-specific actions -----
  async function apply() {
    if (!$currentRepo) return;
    await withBusy(() => ipc.stashApply($currentRepo!, index));
  }
  async function pop() {
    if (!$currentRepo) return;
    await withBusy(() => ipc.stashPop($currentRepo!, index));
    onClose();
  }
  async function drop() {
    if (!$currentRepo) return;
    if (await dropStashAt($currentRepo, index)) onClose();
  }
  async function editMsg() {
    if (!$currentRepo || !entry) return;
    const m = await promptDialog({ title: "Edit stash message:", initial: entry.message, confirmLabel: "Save" });
    if (m === null) return;
    await withBusy(() => ipc.stashEditMessage($currentRepo!, index, m));
  }

  function cycleSort() { sortMode = sortMode === "asc" ? "desc" : "asc"; }
  function sortLabel(): string { return sortMode === "asc" ? "Sort: A→Z" : "Sort: Z→A"; }
  function pathOf(f: FileDiff): string { return f.new_path || f.old_path; }
  const sortedDiffs = $derived.by<FileDiff[]>(() => {
    const arr = diffs.slice();
    arr.sort((a, b) => sortMode === "asc"
      ? pathOf(a).localeCompare(pathOf(b))
      : pathOf(b).localeCompare(pathOf(a)));
    return arr;
  });

  function fmtDate(ts: number): string {
    const d = new Date(ts * 1000);
    const dd = String(d.getDate()).padStart(2, "0");
    const mm = String(d.getMonth() + 1).padStart(2, "0");
    const yy = d.getFullYear();
    const hh = String(d.getHours()).padStart(2, "0");
    const mi = String(d.getMinutes()).padStart(2, "0");
    return `${dd}/${mm}/${yy} @ ${hh}:${mi}`;
  }

  // ----- file tree (same as CommitDetailsPanel) -----
  type TreeNode = {
    name: string; path: string;
    file?: FileDiff;
    children: Map<string, TreeNode>;
  };
  const root = $derived.by<TreeNode>(() => {
    const r: TreeNode = { name: "", path: "", children: new Map() };
    for (const f of diffs) {
      const fp = f.new_path || f.old_path;
      const parts = fp.split("/").filter(Boolean);
      let cur = r;
      for (let i = 0; i < parts.length; i++) {
        const isLeaf = i === parts.length - 1;
        const seg = parts[i];
        let child = cur.children.get(seg);
        if (!child) {
          child = { name: seg, path: parts.slice(0, i + 1).join("/"), children: new Map() };
          cur.children.set(seg, child);
        }
        if (isLeaf) child.file = f;
        cur = child;
      }
    }
    return r;
  });
  function sortedChildren(n: TreeNode): TreeNode[] {
    return [...n.children.values()].sort((a, b) => {
      const aIsDir = !a.file;
      const bIsDir = !b.file;
      if (aIsDir !== bIsDir) return aIsDir ? -1 : 1;
      return sortMode === "asc"
        ? a.name.localeCompare(b.name)
        : b.name.localeCompare(a.name);
    });
  }
  let collapsed = $state<Record<string, boolean>>({});
  function toggle(p: string) { collapsed[p] = !collapsed[p]; }
  function expandAll() {
    collapsed = {};
    allExpanded = !allExpanded;
    if (!allExpanded) {
      const c: Record<string, boolean> = {};
      const walk = (n: TreeNode) => {
        if (!n.file && n.path) c[n.path] = true;
        for (const ch of n.children.values()) walk(ch);
      };
      walk(root);
      collapsed = c;
    }
  }

  function fileChanges(f: FileDiff): { add: number; del: number } {
    let add = 0, del = 0;
    for (const h of f.hunks) for (const l of h.lines) {
      if (l.kind === "add") add++;
      else if (l.kind === "del") del++;
    }
    return { add, del };
  }
</script>

<div class="commit-panel">
  {#if !entry}
    <div class="empty">Stash no longer exists.</div>
  {:else}
    <header class="bar">
      <span class="commit-label">stash:</span>
      <span class="commit-sha">{entry.sha.slice(0, 7)}</span>
      <span class="spacer"></span>
      <button class="close" onclick={onClose} title="Back to changes" aria-label="Back to changes">
        <Icon name="close" size={14} />
      </button>
    </header>

    <div class="subject-box">
      <div class="subject">{cleanedSubject()}</div>
    </div>

    <div class="grip"></div>

    <div class="meta">
      {#if node}
        <div class="author">
          <Avatar email={node.author_email} name={node.author_name} size={32} />
          <div class="author-text">
            <div class="name">{node.author_name}</div>
            <div class="when">stashed {fmtDate(node.timestamp)}</div>
          </div>
        </div>
      {/if}
      <div class="parents">
        {#if node && node.parents.length >= 1}
          <span class="parent-label">parent:</span>
          <span class="parent-sha">{node.parents[0].slice(0, 7)}</span>
        {/if}
      </div>
    </div>

    <div class="files-bar">
      <span class="modified">
        <span class="m-ico"><Icon name="file-modified" size={14} /></span>
        <span class="m-count">{diffs.length}</span>
        <span class="m-lbl">modified</span>
      </span>
      <button class="sort-btn" onclick={cycleSort} title={sortLabel()} aria-label={sortLabel()}><span class:sort-flip={sortMode === "desc"}><Icon name="sort" size={14} /></span></button>
      <span class="seg">
        <button class="seg-btn" class:active={viewMode === "path"} onclick={() => viewMode = "path"}
          title="Path view" aria-label="Path view"><Icon name="file" size={14} /></button>
        <button class="seg-btn" class:active={viewMode === "tree"} onclick={() => viewMode = "tree"}
          title="Tree view" aria-label="Tree view"><Icon name="folder" size={14} /></button>
      </span>
      <label class="ck">
        <input type="checkbox" bind:checked={showDiffs} />
        Show diffs
      </label>
    </div>

    <div class="files-body">
      {#if loading}
        <div class="empty">Loading…</div>
      {:else if diffs.length === 0 && !$diffPrefs.ignoreWs}
        <div class="empty">No changes in stash.</div>
      {:else if showDiffs || diffs.length === 0}
        <!-- Empty with whitespace hidden: DiffViewer shows the toolbar that undoes it. -->
        <DiffViewer {diffs} revs={stashRevs(index)} />
      {:else}
        <div class="expand-row">
          <button class="link" onclick={expandAll}>{allExpanded ? "Collapse All" : "Expand All"}</button>
        </div>
        {#if viewMode === "tree"}
          <ul class="tree">
            {#each sortedChildren(root) as child (child.path)}
              {@render treeNode(child, 0)}
            {/each}
          </ul>
        {:else}
          <ul class="flat">
            {#each sortedDiffs as f (f.new_path || f.old_path)}
              {@const c = fileChanges(f)}
              <li>
                <button class="file-btn" type="button"
                  onclick={() => showCommitFile(entry.sha, f.new_path || f.old_path)}>
                  <span class="f-ico"><Icon name="file-modified" size={16} /></span>
                  <span class="f-count">{c.add + c.del}</span>
                  <span class="f-path">{f.new_path || f.old_path}</span>
                </button>
              </li>
            {/each}
          </ul>
        {/if}
      {/if}
    </div>

    <nav class="actions">
      <button onclick={apply}>Apply</button>
      <button onclick={pop}>Pop</button>
      <button onclick={editMsg}>Edit message</button>
      <button class="danger" onclick={drop}>Delete</button>
    </nav>
  {/if}
</div>

{#snippet treeNode(node: TreeNode, depth: number)}
  {#if node.file}
    {@const c = fileChanges(node.file)}
    {@const fp = node.file.new_path || node.file.old_path}
    <li class="file">
      <button class="file-btn" type="button"
        style="padding-left: {12 + depth * 14}px"
        onclick={() => showCommitFile(entry!.sha, fp)}>
        <span class="f-ico"><Icon name="file-modified" size={16} /></span>
        <span class="f-count">{c.add + c.del}</span>
        <span class="f-path">{node.name}</span>
      </button>
    </li>
  {:else}
    <li class="dir" style="padding-left: {12 + depth * 14}px">
      <button class="dir-toggle" onclick={() => toggle(node.path)}>
        <Icon name={collapsed[node.path] ? "chevron-right" : "chevron-down"} size={14} />
        <span class="name">{node.name}</span>
      </button>
    </li>
    {#if !collapsed[node.path]}
      {#each sortedChildren(node) as ch (ch.path)}
        {@render treeNode(ch, depth + 1)}
      {/each}
    {/if}
  {/if}
{/snippet}

