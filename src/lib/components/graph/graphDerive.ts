// Pure helpers behind GraphCanvas's $derived values. No stores, no DOM: each
// takes the data it reads as parameters so it can be unit-tested with bun.
// The $derived wrappers that call these stay in GraphCanvas.svelte so Svelte
// still tracks every reactive read.
import type { CommitRef, GraphNode, RefKind, StashEntry, StatusEntry } from "$lib/ipc";
import type { GraphCol } from "$lib/stores/layout";
import { ROW_HEIGHT, TOP_PADDING } from "$lib/graph/layout";

// Gutter between two column tracks in the header and row grid.
const GUTTER_PX = 6;

export interface GraphColumnSpec {
  id: GraphCol;
  width: number;
  minWidth: number;
}

export interface WipBreakdown {
  edits: number;
  news: number;
  dels: number;
  conflicts: number;
}

// Maps each sha to its row index in the displayed node list.
export function buildShaToRow(nodes: readonly GraphNode[]): Map<string, number> {
  const m = new Map<string, number>();
  for (let i = 0; i < nodes.length; i++) m.set(nodes[i].sha, i);
  return m;
}

// Refs that paint as badges: every ref except stash entries (see refsAt in
// GraphCanvas.svelte).
export function nonStashRefs(refs: readonly CommitRef[] | undefined): CommitRef[] {
  return (refs ?? []).filter((r) => r.kind !== "stash");
}

// Rows whose refs cell will paint a badge — the renderer draws a stub
// line from the dot toward the badge in the lane color so badge and
// graph visually plug together (#2 of the 2026-04-30 batch).
// Same filter as `refsAt()`: stash refs aren't rendered as badges, so
// they shouldn't trigger the lane→badge stub line either. Without
// this filter, a row whose only ref is `refs/stash` gets a stub drawn
// toward a badge that never appears — line ends mid-air on the left.
export function buildRowsWithRefs(
  nodes: readonly GraphNode[],
  refsByCommit: ReadonlyMap<string, readonly CommitRef[]>,
): Set<number> {
  const s = new Set<number>();
  for (let i = 0; i < nodes.length; i++) {
    if (nonStashRefs(refsByCommit.get(nodes[i].sha)).length > 0) s.add(i);
  }
  return s;
}

// Rows that should render an HTML <Avatar> overlay instead of a canvas
// dot — every regular commit with an author email. Merges keep the
// filled circle so the donut/avatar doesn't fight visually with the
// multi-parent edges joining at it.
export function buildAvatarRows(nodes: readonly GraphNode[]): Set<number> {
  const s = new Set<number>();
  for (let i = 0; i < nodes.length; i++) {
    const n = nodes[i];
    if (n.parents.length >= 2) continue;
    if (!n.author_email) continue;
    s.add(i);
  }
  return s;
}

// Set of stash row indices for the renderer (dashed edges + stash
// glyph). The mapping uses the sha→stash-index lookup that already
// powers the right-panel switch.
export function buildStashRows(
  nodes: readonly GraphNode[],
  stashes: readonly StashEntry[],
): Set<number> {
  const s = new Set<number>();
  const stashShas = new Set(stashes.map((st) => st.sha));
  for (let i = 0; i < nodes.length; i++) {
    if (stashShas.has(nodes[i].sha)) s.add(i);
  }
  return s;
}

// Git's autogenerated stash subjects come in several spellings depending on
// version and which entry of the stash family this is:
//   "WIP on <branch>: <sha> <subject>"
//   "On <branch>: <user message>"
//   "index on <branch>: <sha> <subject>"
//   "untracked files on <branch>: ..."
// Strip whichever prefix matches.
export function stripStashSubject(subject: string): string {
  const m = subject.match(
    /^(?:WIP|wip|On|on|Index|index|Untracked files|untracked files)\s+on\s+[^:]+:\s*(.+)$/,
  ) ?? subject.match(/^On\s+[^:]+:\s*(.+)$/i);
  return m ? m[1] : subject;
}

// #1 round 9: stash commits get an autogenerated subject like
//   "WIP on master: 53deb12 Merge pull request #137"
//   "index on master: 53deb12 ..."
//   "untracked files on master: ..."
// Strip that boilerplate so the row reads as the underlying commit.
export function displaySubjectFor(subject: string, stashIndex: number | null): string {
  if (stashIndex === null) return subject;
  return stripStashSubject(subject);
}

// #10 — synthesize fake CommitRef[] from the containing-branches set so
// RefBadges can render them with the same look (just ghosted).
// Built once per graph load. containingRefs runs per hovered row, and a
// linear refs.find per containing branch name was O(refs) each time. Keeps
// the first ref seen per name, matching the old find() semantics.
export function buildBranchKindByName(refs: readonly CommitRef[]): Map<string, RefKind> {
  const m = new Map<string, RefKind>();
  for (const r of refs) {
    if (r.kind !== "localbranch" && r.kind !== "remotebranch") continue;
    if (!m.has(r.name)) m.set(r.name, r.kind);
  }
  return m;
}

// Ghost refs for one commit: every containing branch name that has a branch
// ref. Kind (local vs remote) comes from the branch ref with this name; names
// with no branch ref are skipped.
export function buildContainingRefs(
  sha: string,
  names: ReadonlySet<string> | undefined,
  branchKindByName: ReadonlyMap<string, RefKind>,
): CommitRef[] {
  if (!names || names.size === 0) return [];
  const out: CommitRef[] = [];
  for (const n of names) {
    const kind = branchKindByName.get(n);
    if (!kind) continue;
    out.push({ name: n, kind, target_sha: sha });
  }
  return out;
}

// #1 round 10: when HEAD is detached (or just checked out a commit), show
// a synthetic "HEAD" pill on the row even if no branch ref points there.
export function withSyntheticHead(
  sha: string,
  direct: CommitRef[],
  headSha: string | null | undefined,
  headBranch: string | null | undefined,
): CommitRef[] {
  if (headSha === sha && !headBranch) {
    // detached: synthesize a HEAD ref so RefBadges renders it as a pill.
    return [
      { name: "HEAD", kind: "head", target_sha: sha },
      ...direct,
    ];
  }
  return direct;
}

// WIP pill breakdown — GitKraken-style. Group `git status` entries by
// semantic kind so the user knows at a glance what's pending without
// opening the changes panel: edits, new files, deletions, conflicts.
export function buildWipBreakdown(status: readonly StatusEntry[]): WipBreakdown {
  let edits = 0, news = 0, dels = 0, conflicts = 0;
  for (const s of status) {
    if (s.conflicted) { conflicts++; continue; }
    const v = s.index !== "unmodified" && s.index !== "untracked" ? s.index : s.worktree;
    switch (v) {
      case "added": case "untracked": case "copied":
        news++; break;
      case "deleted":
        dels++; break;
      case "renamed": case "modified":
      default:
        edits++; break;
    }
  }
  return { edits, news, dels, conflicts };
}

// Narrowest the flexible message column may get before the row scrolls.
export const MSG_FLEX_MIN_PX = 120;

// The commit message column absorbs the remaining width (GitKraken layout):
// with the last column flexing instead, a fixed 360 px message pushed author
// and date out of a narrow center pane. Without a visible message column the
// last column flexes, as before.
function columnTrack(col: GraphCol, flexes: boolean, widthPx: (c: GraphCol) => number): string {
  if (!flexes) return `${widthPx(col)}px`;
  return col === "msg" ? `minmax(${MSG_FLEX_MIN_PX}px, 1fr)` : "1fr";
}

// grid template like "200px 6px 180px 6px minmax(120px, 1fr) 6px 140px"
export function buildGridTemplate(
  order: readonly GraphCol[],
  widthPx: (col: GraphCol) => number,
): string {
  const flexCol = order.includes("msg") ? "msg" : order[order.length - 1];
  const parts: string[] = [];
  for (let i = 0; i < order.length; i++) {
    parts.push(columnTrack(order[i], order[i] === flexCol, widthPx));
    if (i < order.length - 1) parts.push(`${GUTTER_PX}px`);
  }
  return parts.join(" ");
}

// A commit with two or more parents. Shared by the merge dimming and the
// avatar rule above, so "merge" means the same thing everywhere.
export function isMergeNode(node: GraphNode): boolean {
  return node.parents.length >= 2;
}

// Text-dimming rule for one HTML row. A row dims when merge dimming is on and
// it is a merge, or when a ref highlight is active and the row is outside the
// hovered ref's history. Both can apply; either one is enough.
export function isRowDimmed(
  node: GraphNode,
  dimMerges: boolean,
  highlightSet: ReadonlySet<string> | null,
): boolean {
  if (dimMerges && isMergeNode(node)) return true;
  return highlightSet !== null && !highlightSet.has(node.sha);
}

// Px offset of the "graph" column's left edge given the current column order.
export function graphLeftOffset(
  order: readonly GraphCol[],
  widthPx: (col: GraphCol) => number,
): number {
  let x = 0;
  for (const c of order) {
    if (c === "graph") return x;
    x += widthPx(c) + GUTTER_PX;
  }
  return x;
}

// One painted row of the virtual window. `node` is null for the WIP slot.
export interface VisibleRow {
  row: number;
  node: GraphNode | null;
  top: number;
  isWip: boolean;
}

// Rows in the scroll window [start, end). When the WIP row is shown it takes
// row 0 and node i sits at row i + 1; under solo WIP is hidden and node i sits
// at row i. Pure so both mappings are unit-tested.
export function buildVisibleRows(
  range: { start: number; end: number },
  nodes: readonly GraphNode[],
  wipVisible: boolean,
): VisibleRow[] {
  const list: VisibleRow[] = [];
  const wipShift = wipVisible ? 1 : 0;
  for (let r = range.start; r < range.end; r++) {
    const top = TOP_PADDING + r * ROW_HEIGHT;
    if (wipVisible && r === 0) list.push({ row: r, node: null, top, isWip: true });
    else list.push({ row: r, node: nodes[r - wipShift], top, isWip: false });
  }
  return list;
}

// One spec per visible column, in layout order. Hidden columns are not passed in.
export function buildColumnSpecs(
  order: readonly GraphCol[],
  widthPx: (col: GraphCol) => number,
  minWidths: Record<GraphCol, number>,
): GraphColumnSpec[] {
  return order.map((id) => ({ id, width: widthPx(id), minWidth: minWidths[id] }));
}
